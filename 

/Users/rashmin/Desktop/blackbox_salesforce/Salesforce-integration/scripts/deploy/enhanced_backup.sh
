#!/usr/bin/env bash
# =============================================================================
# Enhanced Backup Script for Salesforce CI/CD Pipeline
# =============================================================================
# This script retrieves metadata from the target Salesforce org and backs it up
# with automatic 90-day retention policy.
#
# Features:
# - Dated backup folders (YYYY-MM-DD)
# - Selective metadata backup based on delta package
# - 90-day automatic retention
# - Comprehensive logging
# - Error handling
# =============================================================================

set -euo pipefail

# Color codes for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

# Logging functions
log_info() {
    echo -e "${BLUE}[INFO]${NC} $(date +'%Y-%m-%d %H:%M:%S') $*"
}

log_success() {
    echo -e "${GREEN}[SUCCESS]${NC} $(date +'%Y-%m-%d %H:%M:%S') $*"
}

log_warning() {
    echo -e "${YELLOW}[WARNING]${NC} $(date +'%Y-%m-%d %H:%M:%S') $*"
}

log_error() {
    echo -e "${RED}[ERROR]${NC} $(date +'%Y-%m-%d %H:%M:%S') $*"
}

# Configuration
ROOT_DIR="${ROOT_DIR:-$(cd "$(dirname "$0")/../.." && pwd)}"
TMP_DIR="${TMP_DIR:-$ROOT_DIR/tmp_delta}"
BACKUP_ROOT="${BACKUP_ROOT:-$ROOT_DIR/backup}"
RETENTION_DAYS="${RETENTION_DAYS:-90}"
MANIFEST="${MANIFEST:-$TMP_DIR/package.xml}"

# Create timestamped backup directory
TODAY=$(date +%Y-%m-%d)
BACKUP_DIR="$BACKUP_ROOT/$TODAY"

# Error handler
error_handler() {
    local line_no=$1
    local error_code=$2
    log_error "Error occurred in script at line $line_no, exit code: $error_code"
    log_error "Backup may be incomplete. Check: $BACKUP_DIR"
    exit "$error_code"
}

trap 'error_handler ${LINENO} $?' ERR

# ============================================================================
# Main Function
# ============================================================================
main() {
    log_info "=========================================="
    log_info "  SALESFORCE METADATA BACKUP"
    log_info "=========================================="
    log_info "Date: $TODAY"
    log_info "Retention: $RETENTION_DAYS days"
    log_info "=========================================="

    # Check prerequisites
    check_prerequisites

    # Create backup directory
    create_backup_dir

    # Check manifest
    check_manifest

    # Retrieve metadata
    retrieve_metadata

    # Unzip if needed
    unzip_metadata

    # Apply retention policy
    apply_retention_policy

    # Summary
    print_summary

    log_success "Backup completed successfully!"
}

# ============================================================================
# Check Prerequisites
# ============================================================================
check_prerequisites() {
    log_info "Checking prerequisites..."

    # Check for Salesforce CLI
    if command -v sf >/dev/null 2>&1; then
        log_success "sf CLI found: $(sf --version | head -1)"
    elif command -v sfdx >/dev/null 2>&1; then
        log_warning "sfdx CLI found (legacy): $(sfdx --version | head -1)"
    else
        log_error "Neither sf nor sfdx CLI found. Please install Salesforce CLI."
        exit 1
    fi

    log_success "Prerequisites check passed"
}

# ============================================================================
# Create Backup Directory
# ============================================================================
create_backup_dir() {
    log_info "Creating backup directory: $BACKUP_DIR"
    mkdir -p "$BACKUP_DIR"
    log_success "Backup directory created"
}

# ============================================================================
# Check Manifest
# ============================================================================
check_manifest() {
    if [ ! -f "$MANIFEST" ]; then
        log_warning "Manifest not found at $MANIFEST"
        log_warning "Will retrieve all custom metadata (wildcard)"

        # Create a wildcard manifest
        MANIFEST="$BACKUP_ROOT/full_manifest.xml"
        cat > "$MANIFEST" <<'EOF'
<?xml version="1.0" encoding="UTF-8"?>
<Package xmlns="http://soap.sforce.com/2006/04/metadata">
    <types>
        <members>*</members>
        <name>CustomObject</name>
    </types>
    <types>
        <members>*</members>
        <name>ApexClass</name>
    </types>
    <version>58.0</version>
</Package>
EOF
        log_info "Created wildcard manifest for full backup"
    else
        log_info "Using manifest: $MANIFEST"
    fi
}

# ============================================================================
# Retrieve Metadata
# ============================================================================
retrieve_metadata() {
    log_info "Starting metadata retrieval..."

    local start_time=$(date +%s)

    # Try sf CLI first
    if command -v sf >/dev/null 2>&1; then
        log_info "Using sf CLI for retrieval"

        sf project retrieve start \
            --manifest "$MANIFEST" \
            --target-dir "$BACKUP_DIR" \
            --target-org production-org \
            --wait 30 \
            --json > "$BACKUP_DIR/retrieve_result.json" 2>&1 || {
                log_warning "sf CLI retrieval completed with warnings"
        }
    # Fall back to sfdx
    elif command -v sfdx >/dev/null 2>&1; then
        log_info "Using sfdx CLI for retrieval"

        sfdx force:mdapi:retrieve \
            -k "$MANIFEST" \
            -r "$BACKUP_DIR" \
            --wait 10 \
            --json > "$BACKUP_DIR/retrieve_result.json" || {
                log_warning "sfdx retrieval completed with warnings"
        }
    fi

    local end_time=$(date +%s)
    local duration=$((end_time - start_time))

    log_info "Retrieval completed in ${duration}s"
}

# ============================================================================
# Unzip Metadata
# ============================================================================
unzip_metadata() {
    log_info "Checking for zip files..."

    local zip_count=0

    for zipfile in "$BACKUP_DIR"/*.zip; do
        if [ -f "$zipfile" ]; then
            log_info "Unzipping: $(basename "$zipfile")"
            unzip -o "$zipfile" -d "$BACKUP_DIR" >/dev/null 2>&1 || {
                log_warning "Failed to unzip $zipfile"
            }
            rm -f "$zipfile"
            zip_count=$((zip_count + 1))
        fi
    done

    if [ $zip_count -gt 0 ]; then
        log_success "Unzipped $zip_count file(s)"
    else
        log_info "No zip files found"
    fi
}

# ============================================================================
# Apply Retention Policy
# ============================================================================
apply_retention_policy() {
    log_info "Applying backup retention policy..."

    if [ ! -d "$BACKUP_ROOT" ]; then
        log_warning "Backup root directory not found: $BACKUP_ROOT"
        return
    fi

    # Find directories older than retention period
    local deleted_count=0

    while IFS= read -r -d '' dir; do
        local dir_date=$(basename "$dir")
        log_info "Removing old backup: $dir_date (older than $RETENTION_DAYS days)"
        rm -rf "$dir"
        deleted_count=$((deleted_count + 1))
    done < <(find "$BACKUP_ROOT" -maxdepth 1 -mindepth 1 -type d -mtime +$RETENTION_DAYS -print0)

    if [ $deleted_count -gt 0 ]; then
        log_success "Removed $deleted_count old backup(s)"
    else
        log_info "No old backups to remove"
    fi
}

# ============================================================================
# Print Summary
# ============================================================================
print_summary() {
    log_info "=========================================="
    log_info "  BACKUP SUMMARY"
    log_info "=========================================="

    local total_files=$(find "$BACKUP_DIR" -type f ! -name '*.json' ! -name '*.zip' | wc -l)
    local total_size=$(du -sh "$BACKUP_DIR" | cut -f1)

    log_info "Backup Directory: $BACKUP_DIR"
    log_info "Total Files: $total_files"
    log_info "Total Size: $total_size"

    # Count backups
    local backup_count=$(find "$BACKUP_ROOT" -maxdepth 1 -mindepth 1 -type d | wc -l)
    log_info "Total Backups: $backup_count"

    log_info "=========================================="
}

# Run main function
main "$@"

