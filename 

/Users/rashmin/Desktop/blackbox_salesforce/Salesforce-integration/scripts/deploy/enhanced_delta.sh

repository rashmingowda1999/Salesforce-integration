#!/usr/bin/env bash
# =============================================================================
# Enhanced Delta Generation Script for Salesforce CI/CD Pipeline
# =============================================================================
# This script generates a delta package containing only changed metadata
# components between two git refs using sfdx-git-delta.
#
# Features:
# - Detects Apex, Permission Set, Profile changes
# - Filters managed package components
# - Handles destructive changes
# - Comprehensive logging
# =============================================================================

set -euo pipefail

# Color codes for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
CYAN='\033[0;36m'
NC='\033[0m' # No Color

# Logging functions
log_info() {
    echo -e "${BLUE}[INFO]${NC} $(date +'%Y-%m-%d %H:%M:%S') $*"
}

log_success() {
    echo -e "${GREEN}[SUCCESS]${NC} $(date +'%Y-%m-%d %H:%M:%S') $*"
}

log_warning() {
    echo -e "${YELLOW}[WARNING]${NC} $(date +'%Y-%m-%d %H:%M:%S') $*"
}

log_error() {
    echo -e "${RED}[ERROR]${NC} $(date +'%Y-%m-%d %H:%M:%S') $*"
}

log_step() {
    echo -e "${CYAN}[STEP]${NC} $(date +'%Y-%m-%d %H:%M:%S') $*"
}

# Configuration
ROOT_DIR="${ROOT_DIR:-$(cd "$(dirname "$0")/../.." && pwd)}"
TMP_DIR="${TMP_DIR:-$ROOT_DIR/tmp_delta}"
SOURCE_DIR="${SOURCE_DIR:-$ROOT_DIR/force-app}"

# Default refs
BASE_REF="${BASE_REF:-HEAD~1}"
TO_REF="${TO_REF:-HEAD}"

# Error handler
error_handler() {
    local line_no=$1
    local error_code=$2
    log_error "Error occurred in script at line $line_no, exit code: $error_code"
    exit "$error_code"
}

trap 'error_handler ${LINENO} $?' ERR

# ============================================================================
# Main Function
# ============================================================================
main() {
    log_info "=========================================="
    log_info "  SALESFORCE DELTA GENERATION"
    log_info "=========================================="
    log_info "Base Ref: $BASE_REF"
    log_info "To Ref: $TO_REF"
    log_info "Source: $SOURCE_DIR"
    log_info "Output: $TMP_DIR"
    log_info "=========================================="

    # Create output directory
    create_output_dir

    # Check prerequisites
    check_prerequisites

    # Check for changes
    check_changes

    # Generate delta package
    generate_delta

    # Filter managed packages
    filter_managed_packages

    # Detect change types
    detect_change_types

    # Handle destructive changes
    handle_destructive_changes

    # Print summary
    print_summary

    log_success "Delta generation completed!"
}

# ============================================================================
# Create Output Directory
# ============================================================================
create_output_dir() {
    log_step "Creating output directory..."
    mkdir -p "$TMP_DIR"
    log_success "Output directory: $TMP_DIR"
}

# ============================================================================
# Check Prerequisites
# ============================================================================
check_prerequisites() {
    log_step "Checking prerequisites..."

    # Check git
    if ! command -v git >/dev/null 2>&1; then
        log_error "git not found"
        exit 1
    fi

    # Check for sfdx-git-delta
    if command -v npx >/dev/null 2>&1; then
        log_info "Using npx for sfdx-git-delta"
    elif command -v sf >/dev/null 2>&1; then
        log_info "Using sf CLI"
    else
        log_error "No CLI found"
        exit 1
    fi

    # Check source directory
    if [ ! -d "$SOURCE_DIR" ]; then
        log_error "Source directory not found: $SOURCE_DIR"
        exit 1
    fi

    log_success "Prerequisites check passed"
}

# ============================================================================
# Check for Changes
# ============================================================================
check_changes() {
    log_step "Checking for changes between $BASE_REF and $TO_REF..."

    # Get list of changed files
    CHANGES=$(git diff --name-only "$BASE_REF" "$TO_REF" -- "$SOURCE_DIR/" 2>/dev/null || true)

    if [ -z "$CHANGES" ]; then
        log_warning "No changes detected in $SOURCE_DIR/"
        echo "no_changes=true" > "$TMP_DIR/metadata.json"
        exit 0
    fi

    # Count changes
    CHANGE_COUNT=$(echo "$CHANGES" | wc -l | tr -d ' ')
    log_info "Found $CHANGE_COUNT changed file(s)"

    # Save change list
    echo "$CHANGES" > "$TMP_DIR/changed_files.txt"

    log_success "Changes detected"
}

# ============================================================================
# Generate Delta Package
# ============================================================================
generate_delta() {
    log_step "Generating delta package..."

    local start_time=$(date +%s)

    # Run sfdx-git-delta
    if command -v npx >/dev/null 2>&1; then
        log_info "Running: npx sfdx-git-delta --to $TO_REF --from $BASE_REF --output $TMP_DIR"

        npx sfdx-git-delta \
            --to "$TO_REF" \
            --from "$BASE_REF" \
            --output "$TMP_DIR" \
            --source "$SOURCE_DIR" \
            --generate-delta || {
                log_warning "Delta generation completed with warnings"
        }
    elif command -v sf >/dev/null 2>&1; then
        log_info "Running: sf sgd source delta --to $TO_REF --from $BASE_REF"

        sf sgd source delta \
            --to "$TO_REF" \
            --from "$BASE_REF" \
            --output "$TMP_DIR" \
            --source "$SOURCE_DIR" \
            --generate-delta || {
                log_warning "Delta generation completed with warnings"
        }
    fi

    local end_time=$(date +%s)
    local duration=$((end_time - start_time))

    log_info "Delta generation completed in ${duration}s"

    # Display generated files
    log_info "Generated files:"
    ls -la "$TMP_DIR/"
}

# ============================================================================
# Filter Managed Packages
# ============================================================================
filter_managed_packages() {
    log_step "Filtering managed package components..."

    local pkg_file="$TMP_DIR/package.xml"

    if [ ! -f "$pkg_file" ]; then
        log_warning "No package.xml found, skipping managed package filtering"
        return
    fi

    # Backup original
    cp "$pkg_file" "$pkg_file.bak"

    # Filter out managed package components
    if command -v xmlstarlet >/dev/null 2>&1; then
        log_info "Using xmlstarlet for filtering"
        xmlstarlet ed \
            -d '//types/members[contains(text(), "__")]' \
            "$pkg_file.bak" > "$pkg_file"
    else
        log_warning "No XML tool available, skipping managed package filtering"
        cp "$pkg_file.bak" "$pkg_file"
    fi

    # Cleanup backup
    rm -f "$pkg_file.bak"

    log_success "Managed package filtering completed"
}

# ============================================================================
# Detect Change Types
# ============================================================================
detect_change_types() {
    log_step "Detecting change types..."

    local apex_changed=false
    local permission_sets_changed=false
    local profiles_changed=false

    # Check Apex classes
    if grep -qE "^$SOURCE_DIR/.*\.cls$" "$TMP_DIR/changed_files.txt" 2>/dev/null; then
        apex_changed=true
        log_info "Apex classes changed"
    fi

    # Check Permission Sets
    if grep -qE "^$SOURCE_DIR/.*permissionset$" "$TMP_DIR/changed_files.txt" 2>/dev/null; then
        permission_sets_changed=true
        log_info "Permission sets changed"
    fi

    # Check Profiles
    if grep -qE "^$SOURCE_DIR/.*\.profile-meta\.xml$" "$TMP_DIR/changed_files.txt" 2>/dev/null; then
        profiles_changed=true
        log_info "Profiles changed"
    fi

    # Save metadata
    cat > "$TMP_DIR/metadata.json" <<EOF
{
    "base_ref": "$BASE_REF",
    "to_ref": "$TO_REF",
    "change_count": $CHANGE_COUNT,
    "apex_changed": $apex_changed,
    "permission_sets_changed": $permission_sets_changed,
    "profiles_changed": $profiles_changed,
    "has_changes": true
}
EOF

    # Create flag files for pipeline
    [ "$apex_changed" = true ] && touch "$TMP_DIR/apex_changed.flag"
    [ "$permission_sets_changed" = true ] && touch "$TMP_DIR/permissionsets_changed.flag"
    [ "$profiles_changed" = true ] && touch "$TMP_DIR/profiles_changed.flag"

    log_success "Change detection completed"
}

# ============================================================================
# Handle Destructive Changes
# ============================================================================
handle_destructive_changes() {
    log_step "Handling destructive changes..."

    # Check for pre-destructive changes
    if [ -f "$TMP_DIR/destructiveChanges.xml" ]; then
        log_info "Found pre-destructive changes: destructiveChanges.xml"
        cp "$TMP_DIR/destructiveChanges.xml" "$TMP_DIR/pre-destructiveChanges.xml"
    fi

    # Check for post-destructive changes
    if [ -f "$TMP_DIR/destructiveChangesPost.xml" ]; then
        log_info "Found post-destructive changes: destructiveChangesPost.xml"
        cp "$TMP_DIR/destructiveChangesPost.xml" "$TMP_DIR/post-destructiveChanges.xml"
    fi

    log_success "Destructive changes handled"
}

# ============================================================================
# Print Summary
# ============================================================================
print_summary() {
    log_info "=========================================="
    log_info "  DELTA GENERATION SUMMARY"
    log_info "=========================================="

    log_info "Base Ref: $BASE_REF"
    log_info "To Ref: $TO_REF"
    log_info "Changed Files: $CHANGE_COUNT"

    # Check package.xml
    if [ -f "$TMP_DIR/package.xml" ]; then
        local pkg_count=$(grep -c '<members>' "$TMP_DIR/package.xml" 2>/dev/null || echo "0")
        log_info "Package Members: $pkg_count"
    fi

    # Flag files
    log_info "Change Flags:"
    [ -f "$TMP_DIR/apex_changed.flag" ] && log_info "  ✓ Apex changed"
    [ -f "$TMP_DIR/permissionsets_changed.flag" ] && log_info "  ✓ Permission Sets changed"
    [ -f "$TMP_DIR/profiles_changed.flag" ] && log_info "  ✓ Profiles changed"

    log_info "=========================================="
}

# Run main function
main "$@"

